<script setup>
import { Head, Link, router } from '@inertiajs/vue3';
import ErpLayout from '@/Components/ErpLayout.vue';
import Card from '@/Components/Cards/Card.vue';

const props = defineProps({
    types: { type: Array, default: () => [] },
    type: { type: String, default: null },
    snapshots: { type: Array, default: () => [] },
});

const statusStyles = {
    pending: 'bg-amber-100 text-amber-700',
    completed: 'bg-emerald-100 text-emerald-700',
    failed: 'bg-red-100 text-red-700',
};

const formatGeneratedAt = (value) => (value ? new Date(value).toLocaleString() : null);

const openable = (snapshot) => snapshot.status === 'completed';

const regenerate = (snapshot) => {
    if (!window.confirm(`Regenerate "${snapshot.title}"? This starts a fresh run; the current snapshot stays in history.`)) {
        return;
    }
    router.post(`/erp/reports/${snapshot.id}/regenerate`, {}, { preserveScroll: true });
};
</script>

<template>
    <ErpLayout>
        <Head title="Snapshot history" />

        <header class="mb-6">
            <h1 class="text-2xl font-bold text-slate-900">Snapshot history</h1>
            <p class="mt-1 text-sm text-slate-500">
                Every past run of each report, newest first, with its status, generator and any
                failure message. Completed runs can be opened or exported as CSV; failed runs can be
                regenerated.
            </p>
        </header>

        <div class="mb-6 flex flex-wrap items-center gap-2">
            <Link
                :href="'/erp/reports/history'"
                class="rounded-full px-3 py-1 text-sm font-medium transition"
                :class="type === null ? 'bg-brand-600 text-white' : 'bg-white text-slate-600 ring-1 ring-slate-200 hover:bg-slate-50'"
            >All</Link>
            <Link
                v-for="report in types"
                :key="report.type"
                :href="`/erp/reports/history?type=${report.type}`"
                class="rounded-full px-3 py-1 text-sm font-medium transition"
                :class="type === report.type ? 'bg-brand-600 text-white' : 'bg-white text-slate-600 ring-1 ring-slate-200 hover:bg-slate-50'"
            >{{ report.label }}</Link>
        </div>

        <Card>
            <div class="overflow-x-auto">
                <table class="min-w-full divide-y divide-slate-200 text-sm">
                    <thead>
                        <tr class="text-left text-xs font-semibold uppercase tracking-wider text-slate-500">
                            <th class="px-3 py-2">#</th>
                            <th class="px-3 py-2">Report</th>
                            <th class="px-3 py-2">Status</th>
                            <th class="px-3 py-2">Generated by</th>
                            <th class="px-3 py-2">Generated at</th>
                            <th class="px-3 py-2">Error</th>
                            <th class="px-3 py-2 text-right">Actions</th>
                        </tr>
                    </thead>
                    <tbody class="divide-y divide-slate-100">
                        <tr v-for="snapshot in snapshots" :key="snapshot.id">
                            <td class="px-3 py-3 text-slate-400">{{ snapshot.id }}</td>
                            <td class="px-3 py-3">
                                <p class="font-medium text-slate-900">{{ snapshot.title }}</p>
                                <p class="text-xs text-slate-400">{{ snapshot.type_label }}</p>
                            </td>
                            <td class="px-3 py-3">
                                <span
                                    class="rounded-full px-2 py-0.5 text-xs font-semibold"
                                    :class="statusStyles[snapshot.status] || 'bg-slate-100 text-slate-600'"
                                >{{ snapshot.status_label }}</span>
                            </td>
                            <td class="px-3 py-3 text-slate-600">
                                {{ snapshot.generated_by ?? '—' }}
                            </td>
                            <td class="px-3 py-3 text-slate-600">
                                {{ formatGeneratedAt(snapshot.generated_at) }}
                            </td>
                            <td class="max-w-xs px-3 py-3">
                                <p
                                    v-if="snapshot.error"
                                    class="rounded bg-red-50 px-2 py-1 text-xs text-red-600"
                                >{{ snapshot.error }}</p>
                                <span v-else class="text-slate-300">—</span>
                            </td>
                            <td class="px-3 py-3">
                                <div class="flex flex-wrap items-center justify-end gap-2">
                                    <Link
                                        v-if="openable(snapshot)"
                                        :href="`/erp/reports/${snapshot.id}`"
                                        class="rounded-lg border border-slate-300 px-2.5 py-1 text-xs font-semibold text-slate-700 transition hover:bg-slate-50"
                                    >Open</Link>
                                    <a
                                        v-if="openable(snapshot)"
                                        :href="`/erp/reports/${snapshot.id}/export`"
                                        class="rounded-lg bg-brand-600 px-2.5 py-1 text-xs font-semibold text-white transition hover:bg-brand-700"
                                    >Export CSV</a>
                                    <button
                                        v-if="snapshot.status === 'completed' || snapshot.status === 'failed'"
                                        type="button"
                                        class="rounded-lg border border-slate-300 px-2.5 py-1 text-xs font-semibold text-slate-700 transition hover:bg-slate-50"
                                        @click="regenerate(snapshot)"
                                    >Regenerate</button>
                                </div>
                            </td>
                        </tr>
                        <tr v-if="snapshots.length === 0">
                            <td colspan="7" class="px-3 py-10 text-center text-slate-400">
                                No snapshots yet — run this report from the library to see history.
                            </td>
                        </tr>
                    </tbody>
                </table>
            </div>
        </Card>
    </ErpLayout>
</template>
